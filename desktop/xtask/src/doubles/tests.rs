//! The doubles ratchet's count of `Cargo.lock`, its baseline and its verdicts (gaps row A18).

use super::*;

/// Versions from names and their versions, as given.
fn versions(list: &[(&str, &[&str])]) -> Versions {
    list.iter()
        .map(|(name, v)| (name.to_string(), v.iter().map(|s| s.to_string()).collect()))
        .collect()
}

/// A `Cargo.lock` as Cargo writes one (the sources and checksums left out: they are not read).
const LOCK_TEXT: &str = r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "dm-core"
version = "0.10.0"
dependencies = [
 "rand 0.8.8",
 "toml",
]

[[package]]
name = "rand"
version = "0.10.2"

[[package]]
name = "rand"
version = "0.8.8"

[[package]]
name = "rand"
version = "0.9.5"

[[package]]
name = "toml"
version = "1.1.5+spec-1.1.0"

[[package]]
name = "toml"
version = "0.8.23"
"#;

#[test]
fn the_lock_is_counted_by_name_its_versions_oldest_first() {
    let all = locked(LOCK_TEXT).unwrap();
    assert_eq!(
        all,
        versions(&[
            ("dm-core", &["0.10.0"]),
            // 0.10 after 0.9: each number compared as a number, not as text.
            ("rand", &["0.8.8", "0.9.5", "0.10.2"]),
            ("toml", &["0.8.23", "1.1.5+spec-1.1.0"]),
        ])
    );
    assert_eq!(
        doubles(all),
        versions(&[
            ("rand", &["0.8.8", "0.9.5", "0.10.2"]),
            ("toml", &["0.8.23", "1.1.5+spec-1.1.0"]),
        ])
    );
    assert!(locked("version = 4\n").is_err());
    assert!(locked("[[package]]\nname = \"a\"\n").is_err());
    assert!(locked("not toml at all [").is_err());
}

#[test]
fn versions_sort_by_their_numbers_then_what_follows() {
    let mut list = [
        "0.14.1-zed",
        "1.0.0",
        "0.14.1",
        "0.2.0",
        "0.14.10",
        "0.14.2",
    ];
    list.sort_by_key(|v| order(v));
    assert_eq!(
        list,
        [
            "0.2.0",
            "0.14.1",
            "0.14.1-zed",
            "0.14.2",
            "0.14.10",
            "1.0.0"
        ]
    );
}

#[test]
fn the_baseline_reads_back_what_it_writes() {
    let written = versions(&[
        ("windows", &["0.57.0", "0.58.0", "0.61.3", "0.62.2"]),
        ("aes", &["0.8.4", "0.9.3"]),
    ]);
    let text = render(&written);
    assert!(text.starts_with(HEADER));
    assert!(text.ends_with("aes 0.8.4 0.9.3\nwindows 0.57.0 0.58.0 0.61.3 0.62.2\n"));
    assert_eq!(parse(&text).unwrap(), written);
    // A name with one version is no double, a name twice is a mistake.
    assert!(parse("aes 0.8.4\n").is_err());
    assert!(parse("aes\n").is_err());
    assert!(parse("aes 0.8.4 0.9.3\naes 0.8.4 0.9.3\n").is_err());
    assert_eq!(parse("# a comment\n\n").unwrap(), Versions::new());
}

#[test]
fn a_new_double_or_a_version_more_fails_and_fewer_is_only_said() {
    let allowed = versions(&[
        ("rand", &["0.8.8", "0.9.5"]),
        ("windows", &["0.57.0", "0.58.0", "0.62.2"]),
        ("dirs", &["6.0.0", "7.0.0"]),
        ("toml", &["0.8.23", "1.1.5"]),
        ("base64", &["0.22.1", "0.23.1"]),
    ]);
    let now = versions(&[
        // A version more than listed.
        ("rand", &["0.8.8", "0.9.5", "0.10.2"]),
        // One fewer.
        ("windows", &["0.58.0", "0.62.2"]),
        // As many, but moved by an update.
        ("toml", &["0.8.23", "1.2.0"]),
        // As listed.
        ("base64", &["0.22.1", "0.23.1"]),
        // Not listed.
        ("hashbrown", &["0.14.5", "0.16.1"]),
        // `dirs` is in one version now, so not here.
    ]);
    let verdict = judge(&now, &allowed);
    assert_eq!(verdict.wrong.len(), 2, "{:?}", verdict.wrong);
    assert!(verdict.wrong.iter().any(|w| w.starts_with("hashbrown ")
        && w.contains("does not name it")
        && w.contains("--grow")));
    assert!(verdict
        .wrong
        .iter()
        .any(|w| w.starts_with("rand ") && w.contains("3 versions") && w.contains("than the 2")));
    assert_eq!(verdict.notes.len(), 3, "{:?}", verdict.notes);
    assert!(verdict
        .notes
        .iter()
        .any(|n| n.starts_with("windows is down to 2 versions") && n.contains("from 3")));
    assert!(verdict
        .notes
        .iter()
        .any(|n| n.starts_with("toml is in versions 0.8.23, 1.2.0 now")));
    assert!(verdict
        .notes
        .iter()
        .any(|n| n.starts_with("dirs is in one version now")));
    // Nothing doubled beyond the baseline: nothing fails and nothing is said.
    let verdict = judge(&allowed, &allowed);
    assert!(verdict.wrong.is_empty() && verdict.notes.is_empty());
}

#[test]
fn the_rewrite_only_shortens_unless_told_to_grow() {
    let allowed = versions(&[
        ("rand", &["0.8.8", "0.9.5"]),
        ("windows", &["0.57.0", "0.58.0", "0.62.2"]),
        ("dirs", &["6.0.0", "7.0.0"]),
        ("toml", &["0.8.23", "1.1.5"]),
    ]);
    let now = versions(&[
        ("rand", &["0.8.8", "0.9.5", "0.10.2"]),
        ("windows", &["0.58.0", "0.62.2"]),
        ("toml", &["0.8.23", "1.2.0"]),
        ("hashbrown", &["0.14.5", "0.16.1"]),
    ]);
    let (written, grown) = shrunk(&now, &allowed);
    assert_eq!(
        written,
        versions(&[
            // Grown: kept as it was, so the check still fails for it.
            ("rand", &["0.8.8", "0.9.5"]),
            // Shortened, and brought up to date.
            ("windows", &["0.58.0", "0.62.2"]),
            ("toml", &["0.8.23", "1.2.0"]),
            // `dirs` removed; `hashbrown` not added.
        ])
    );
    assert_eq!(
        grown,
        ["rand 0.8.8 0.9.5 0.10.2", "hashbrown 0.14.5 0.16.1"]
    );
    // What the rewrite writes passes the check against the lock it was written from, but for
    // what grew.
    let verdict = judge(&now, &written);
    assert_eq!(verdict.wrong.len(), 2);
    assert!(verdict.notes.is_empty(), "{:?}", verdict.notes);
    // Brought down again to what it wrote, nothing changes and nothing has grown.
    let (again, grown) = shrunk(&written, &allowed);
    assert_eq!(again, written);
    assert!(grown.is_empty());
}

/// The checked-in baseline is in the order and form `cargo xtask doubles-baseline` writes, so
/// shortening it changes only its own lines. That the lock holds no more than it lists is
/// `cargo xtask layers`'s check (`the_crates_are_layered_as_they_should_be`).
#[test]
fn the_baseline_is_written_as_the_ratchet_writes_it() {
    let root = crate::root();
    let text = crate::read(&root.join(BASELINE))
        .unwrap()
        .replace("\r\n", "\n");
    let allowed = parse(&text).unwrap();
    assert_eq!(render(&allowed), text);
    for versions in allowed.values() {
        let mut sorted = versions.clone();
        sorted.sort_by_key(|v| order(v));
        assert_eq!(&sorted, versions, "each entry's versions oldest first");
    }
}
